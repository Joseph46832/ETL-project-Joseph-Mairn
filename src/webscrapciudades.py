def extraer_ciudades(texto):
    # Usamos expresiones regulares para sacar solo los nombres entre comillas
    # ignorando "mapeo_paises =" y los dos puntos
    ciudades = re.findall(r'"([^"]+)":', texto)
    return ciudades

def buscar_pais_wikipedia(ciudad):
    # Formateamos el nombre de la ciudad para la URL de Wikipedia
    # Ejemplo: "kingston upon hull" -> "Kingston_upon_Hull"
    ciudad_url = ciudad.title().replace(" ", "_")
    url = f"https://en.wikipedia.org/wiki/{ciudad_url}"
    
    headers = {
        'User-Agent': 'Mozilla/5.0 (Windows NT 10.0; Win64; x64)'
    }
    
    try:
        respuesta = requests.get(url, headers=headers)
        
        if respuesta.status_code == 200:
            soup = BeautifulSoup(respuesta.text, 'html.parser')
            
            # Buscamos la tabla de informacion a la derecha de Wikipedia
            infobox = soup.find('table', class_='infobox')
            
            if infobox:
                # Buscamos todas las filas de la tabla
                for fila in infobox.find_all('tr'):
                    encabezado = fila.find('th')
                    # Si el encabezado dice "Country" o "Sovereign state"
                    if encabezado and ('Country' in encabezado.text or 'State' in encabezado.text):
                        dato = fila.find('td')
                        if dato:
                            pais = dato.text.strip()
                            # Limpiamos referencias de Wikipedia como "Canada[1]" -> "Canada"
                            pais = pais.split('[')[0]
                            return pais
            
            return "No encontrado en Infobox"
        else:
            return f"Error HTTP {respuesta.status_code}"
            
    except Exception as e:
        return "Error de conexion"
