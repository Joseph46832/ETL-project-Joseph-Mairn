    if not os.path.exists(ruta_bronze):
        raise FileNotFoundError(f"No se encontró el archivo Bronze: {ruta_bronze}")
        
    df = pd.read_csv(ruta_bronze)
    print(f"¡Carga exitosa! {df.shape[0]} registros leídos.")
